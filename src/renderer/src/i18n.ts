const messages: Record<UiLanguage, Record<MessageKey, string>> = { zh, en }

export type Translator = (key: MessageKey, values?: Record<string, string | number>) => string

export function translator(language: UiLanguage): Translator {
  return (key, values = {}) => Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    messages[language][key]
  )
}

export function localeTag(language: UiLanguage): string {
  return language === 'en' ? 'en-US' : 'zh-CN'
}

export function providerName(provider: Provider, t: Translator): string {
  return t(provider === 'demo' ? 'providerDemo' : provider === 'qwen' ? 'providerQwen' : 'providerVolcano')
}
